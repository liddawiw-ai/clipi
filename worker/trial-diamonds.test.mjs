import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {trialAccount} from './trial-diamonds.mjs';
import {roomStore} from './room-controls.mjs';
import {readWallet} from './diamond-wallet.mjs';
test('verified owner number grants once, sandbox credits and game or gift retries stay outside purchased diamonds',async()=>{
  const sql=new DatabaseSync(':memory:');
  const db={prepare(query){return {query,bind(...args){const st=sql.prepare(query);return {run:()=>({meta:st.run(...args)}),all:()=>({results:st.all(...args)}),first:()=>st.get(...args)};}};},batch(rows){rows.forEach(r=>sql.exec(r.query));}};
  const q=await roomStore(db);let now=400000000;
  const api=(uid,op,more={})=>trialAccount(q,uid,'owner',{op,...more},(v,status=200)=>({...v,status}),now);
  assert.equal((await api('owner','trialRead')).owner,null);
  await q('INSERT INTO public_numbers VALUES(?,?,0)','9056366','owner').run();
  assert.equal((await api('owner','trialRead')).owner,1000000);
  const gift={bucket:'owner',nonce:crypto.randomUUID(),gift:'وردة حمراء'};
  assert.equal((await api('guest','trialGift',gift)).status,403);assert.equal((await api('admin','trialRead',{number:'9056366'})).owner,null);
  for(let i=0;i<3;i++)assert.equal((await api('owner','trialGift',gift)).owner,999990);
  assert.equal((await api('owner','trialRead')).owner,999990);
  assert.equal((await api('owner','trialGift',{...gift,gift:'قلب'})).status,409);
  const topup={nonce:crypto.randomUUID(),usd:5};
  for(let i=0;i<2;i++)assert.equal((await api('guest','trialTopup',topup)).sandbox,5000);
  const round=Math.floor(now/40000);let seed=(Math.imul(round,1664525)+1013904223)>>>0;const pick=((seed^(seed>>>16))>>>0)%8;
  const bet={bucket:'owner',nonce:crypto.randomUUID(),pick,round,amount:10};
  for(let i=0;i<2;i++)assert.equal((await api('owner','trialPlay',bet)).owner,999980);
  now+=37000;const end=999980+10*[5,10,5,15,5,25,5,45][pick];
  assert.equal((await api('owner','trialRead')).owner,end);
  assert.equal((await api('owner','trialPlay',bet)).owner,end);
  assert.equal((await api('owner','trialPlay',{...bet,nonce:crypto.randomUUID()})).status,409);
  assert.equal((await api('owner','trialRead')).owner,end);
  assert.equal((await readWallet(q,'owner')).diamonds,0);
  assert.equal((await q('SELECT count(*) AS n FROM paid_room_gift').first()).n,0);
  assert.equal((await q('SELECT count(*) AS n FROM clipi_agency_statement').first()).n,0);
});
